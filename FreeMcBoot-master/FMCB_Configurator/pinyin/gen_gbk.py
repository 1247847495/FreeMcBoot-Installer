#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""
gen_gbk.py - 生成 cn_gbk.c / cn_gbk.h（GBK 双向映射表）

背景: 字库存储 SJIS 码位、渲染简体字形 (gen_font.py 的 to_display)。
50009 中文机 OSDSYS 按 GBK 解读 CNF 里的名字字节，因此"5009专用"
输入页提交时必须把候选字的 SJIS 码转换为**显示字符**的 GBK 编码。

生成三张表:
  cn_gbk_codes[]  GBK 码升序       -> 渲染: GBK字节 -> 字形 (经 cn_gbk_sjis -> cn_font_find)
  cn_gbk_sjis[]   与上表平行的 SJIS 码
  cn_sjis_gbk[]   与 cn_font_codes 平行 (按下标), 提交: SJIS -> GBK, 0=无映射

校验:
  1. 与 SJIS 码表零 16 位码冲突 (冲突的 GBK 项从渲染表剔除, 提交表保留)
  2. 14 条常用词组逐字全部可映射
  3. 符号页 78 个符号全部可映射 (ASCII 除外)
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.normpath(os.path.join(HERE, '..'))
sys.path.insert(0, HERE)
from gen_font import to_display

def load_charset():
    entries = []  # (sjis, unicode char)
    with open(os.path.join(HERE, 'charset.txt'), encoding='utf-8') as f:
        for line in f:
            p = line.rstrip('\n').split('\t')
            if len(p) >= 3 and p[1].startswith('U+'):
                entries.append((int(p[0], 16), chr(int(p[1][2:], 16))))
    entries.sort(key=lambda e: e[0])
    return entries

def main():
    # 对齐基准: cn_font.c 的 cn_font_codes (含后补的 ASCII '.', charset.txt 不含)
    fsrc = open(os.path.join(SRC, 'cn_font.c'), encoding='utf-8').read()
    m = re.search(r'cn_font_codes\[CN_FONT_COUNT\]\s*=\s*\{(.*?)\};', fsrc, re.S)
    font_codes = [int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]{4})', m.group(1))]
    assert font_codes == sorted(font_codes), 'cn_font_codes 非升序'

    # charset: sjis -> 存储字符 (用于查显示形)
    ch_of = {}
    for line in open(os.path.join(HERE, 'charset.txt'), encoding='utf-8'):
        p = line.rstrip('\n').split('\t')
        if len(p) >= 3 and p[1].startswith('U+'):
            ch_of[int(p[0], 16)] = chr(int(p[1][2:], 16))
    ch_of[0x9867] = '卡'  #中文特有字，与 gen_font.py 固定追加同步
    missing = [hex(c) for c in font_codes if c >= 0x80 and c not in ch_of]
    assert not missing, '字体码不在 charset.txt: %s' % missing

    sjis_codes = font_codes
    sjis_set = set(sjis_codes)

    # 提交表: 与 cn_font_codes 平行
    sjis_gbk = []          # index 对齐 cn_font_codes
    # 渲染表: (gbk, sjis) gbk 升序且唯一
    gbk_map = {}           # gbk -> sjis
    for sjis in font_codes:
        code = 0
        if sjis >= 0x80:
            disp = to_display(ch_of[sjis])
            try:
                b = disp.encode('gbk')
                if len(b) == 2:
                    code = (b[0] << 8) | b[1]
            except UnicodeEncodeError:
                pass
        sjis_gbk.append(code)
        if code and code not in gbk_map:
            gbk_map[code] = sjis
    # 冲突检测: GBK 码撞 SJIS 码 -> 从渲染表剔除 (提交表保留, 字节仍正确)
    collisions = sorted(set(gbk_map) & sjis_set)
    for c in collisions:
        del gbk_map[c]

    by_gbk = sorted(gbk_map.items())

    # ---- 词组校验: 解析 cn_pinyin.c 的 cn_com_phrases (SJIS 字节), 逐字可提交 ----
    py_src = open(os.path.join(SRC, 'cn_pinyin.c'), encoding='utf-8').read()
    m = re.search(r'cn_com_phrases\[CN_COM_COUNT\]\s*=\s*\{(.*?)\};', py_src, re.S)
    lits = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))
    phrases = [bytes(int(x, 16) for x in re.findall(r'\\x([0-9A-Fa-f]{2})', lit))
               for lit in lits]
    idx_of = {s: i for i, s in enumerate(font_codes)}
    bad = []
    for ph in phrases:
        for k in range(0, len(ph) - 1, 2):
            s = (ph[k] << 8) | ph[k+1]
            if s >= 0x80 and (s not in idx_of or sjis_gbk[idx_of[s]] == 0):
                bad.append('%04X' % s)
    assert not bad, '词组字符无法映射到 GBK: %s' % bad

    # ---- 符号页校验: 解析 cn_pinyin.c 的 cn_sym_codes ----
    sym_m = re.search(r'cn_sym_codes\[CN_SYM_COUNT\]\s*=\s*\{(.*?)\};', py_src, re.S)
    sym = [int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]{4})', sym_m.group(1))]
    bads = [hex(s) for s in sym
            if s >= 0x80 and (s not in idx_of or sjis_gbk[idx_of[s]] == 0)]
    assert not bads, '符号无法映射到 GBK: %s' % bads

    # ---- 输出 ----
    n = len(by_gbk)
    with open(os.path.join(SRC, 'cn_gbk.h'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('//Auto-generated by gen_gbk.py. DO NOT EDIT.\n')
        f.write('#ifndef CN_GBK_H\n#define CN_GBK_H\n\n')
        f.write('#define CN_GBK_COUNT %d\n\n' % n)
        f.write('extern const unsigned short cn_gbk_codes[CN_GBK_COUNT];  //GBK codes, ascending\n')
        f.write('extern const unsigned short cn_gbk_sjis[CN_GBK_COUNT];   //matching SJIS font codes\n')
        f.write('extern const unsigned short cn_sjis_gbk[CN_FONT_COUNT];  //parallel to cn_font_codes; 0=no GBK\n\n')
        f.write('#endif\n')
    with open(os.path.join(SRC, 'cn_gbk.c'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('//Auto-generated by gen_gbk.py. DO NOT EDIT.\n')
        f.write('#include "cn_font.h"\n#include "cn_gbk.h"\n\n')
        f.write('const unsigned short cn_gbk_codes[CN_GBK_COUNT] = {\n')
        for i in range(0, n, 10):
            f.write('\t' + ','.join('0x%04X' % c for c, _ in by_gbk[i:i+10]) + ',\n')
        f.write('};\n\n')
        f.write('const unsigned short cn_gbk_sjis[CN_GBK_COUNT] = {\n')
        for i in range(0, n, 10):
            f.write('\t' + ','.join('0x%04X' % s for _, s in by_gbk[i:i+10]) + ',\n')
        f.write('};\n\n')
        f.write('const unsigned short cn_sjis_gbk[CN_FONT_COUNT] = {\n')
        for i in range(0, len(sjis_gbk), 10):
            f.write('\t' + ','.join('0x%04X' % c for c in sjis_gbk[i:i+10]) + ',\n')
        f.write('};\n')

    mapped = sum(1 for c in sjis_gbk if c)
    print('OK: 渲染表 %d 项, 提交表 %d/%d 字可映射, 码冲突剔除 %d 项: %s'
          % (n, mapped, len(sjis_gbk), len(collisions),
             ' '.join('%04X' % c for c in collisions) or '(无)'))

if __name__ == '__main__':
    main()
